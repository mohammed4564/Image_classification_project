from flask import Flask

from routes.image_routes import image_bp


# ==========================================================
# CREATE FLASK APP
# ==========================================================

app = Flask(__name__)


# ==========================================================
# REGISTER BLUEPRINT
# ==========================================================

app.register_blueprint(
    image_bp
)


# ==========================================================
# RUN APPLICATION
# ==========================================================

if __name__ == "__main__":

    app.run(
        debug=True,
        host="0.0.0.0",
        port=5000
    )